'use client';

import { lazy, Suspense, type ComponentPropsWithoutRef } from 'react';
import type { ExtraProps } from 'react-markdown';
import { useTranslation } from 'react-i18next';
import { PlacePhotoWrapper } from './markdown-place-photo';
import { ReasoningScroll } from './ReasoningScroll';
import { MarkdownCardBinding } from './markdown-card-actions';
import { MarkdownWeatherSeries } from './markdown-weather-series';
import { MarkdownRouteMap } from './markdown-route-map';
import { MarkdownPlacePosition } from './markdown-place-position';

// MCP Apps widget — lazy loaded (only needed when MCP App sentinel divs are present)
const McpAppWidget = lazy(() =>
  import('@/components/chat/McpAppWidget').then(m => ({ default: m.McpAppWidget }))
);

// Skill Apps widget — lazy loaded (only needed when Skill App sentinel divs are present)
const SkillAppWidget = lazy(() =>
  import('@/components/chat/SkillAppWidget').then(m => ({ default: m.SkillAppWidget }))
);

// Interactive page widget — lazy loaded (only needed when a page sentinel is present)
const PageAppWidget = lazy(() =>
  import('@/components/chat/PageAppWidget').then(m => ({ default: m.PageAppWidget }))
);

type MarkdownDivProps = ComponentPropsWithoutRef<'div'> & ExtraProps;

function renderNativePresentation({ className, children, node, ...props }: MarkdownDivProps) {
  const classes = new Set(className?.split(/\s+/));
  if (classes.has('lia-card-binding')) {
    return (
      <MarkdownCardBinding {...props} className={className} node={node}>
        {children}
      </MarkdownCardBinding>
    );
  }
  if (classes.has('lia-weather-series')) {
    return (
      <MarkdownWeatherSeries {...props} className={className} node={node}>
        {children}
      </MarkdownWeatherSeries>
    );
  }
  if (classes.has('lia-route-map')) {
    return (
      <MarkdownRouteMap {...props} className={className} node={node}>
        {children}
      </MarkdownRouteMap>
    );
  }
  if (classes.has('lia-place-position')) {
    return (
      <MarkdownPlacePosition {...props} className={className} node={node}>
        {children}
      </MarkdownPlacePosition>
    );
  }
  return null;
}

/** Preserve widget lifetimes when the surrounding Markdown renders again. */
export function MarkdownDiv({ className, children, node: _node, ...props }: MarkdownDivProps) {
  const { t } = useTranslation();
  const presentation = renderNativePresentation({ className, children, node: _node, ...props });
  if (presentation) return presentation;
  // Live reasoning block (💭) — emitted by the SSE reasoning handler
  // as <div class="lia-reasoning">. Wrap in a fixed-height, auto-
  // scrolling container so the streamed thoughts scroll smoothly
  // (no jump) instead of pushing the page.
  if (className?.includes('lia-reasoning')) {
    return <ReasoningScroll>{children}</ReasoningScroll>;
  }

  // MCP App widget (generated by mcp_app_sentinel.py)
  // Replaces sentinel div with interactive sandboxed iframe + JSON-RPC bridge
  if (className?.includes('lia-mcp-app')) {
    const registryId = (props as Record<string, unknown>)['data-registry-id'] as string | undefined;
    if (registryId) {
      return (
        <Suspense
          fallback={
            <div className="lia-mcp-app__placeholder">
              <div className="lia-mcp-app__loading">{t('mcp_apps.loading')}</div>
            </div>
          }
        >
          <McpAppWidget registryId={registryId} />
        </Suspense>
      );
    }
  }

  // Skill App widget (generated by skill_app_sentinel.py)
  // Replaces sentinel div with iframe (frame.html/url) and/or image card
  if (className?.includes('lia-skill-app')) {
    const registryId = (props as Record<string, unknown>)['data-registry-id'] as string | undefined;
    if (registryId) {
      return (
        <Suspense
          fallback={
            <div className="lia-skill-app__placeholder">
              <div className="lia-skill-app__loading">
                {t('skill_apps.loading', { defaultValue: 'Loading skill…' })}
              </div>
            </div>
          }
        >
          <SkillAppWidget registryId={registryId} />
        </Suspense>
      );
    }
  }

  // Interactive page (generated by page_app_sentinel.py)
  if (className?.split(/\s+/).includes('lia-page-app')) {
    const registryId = (props as Record<string, unknown>)['data-registry-id'] as string | undefined;
    if (registryId) {
      return (
        <Suspense fallback={null}>
          <PageAppWidget registryId={registryId} />
        </Suspense>
      );
    }
  }

  // Place photo gallery (generated by place_card.py)
  // Uses PlacePhotoWrapper for multi-image gallery lightbox
  if (className?.split(/\s+/).includes('lia-place__photo')) {
    return (
      <PlacePhotoWrapper className={className} {...props}>
        {children}
      </PlacePhotoWrapper>
    );
  }

  // Default div rendering
  return (
    <div className={className} {...props}>
      {children}
    </div>
  );
}

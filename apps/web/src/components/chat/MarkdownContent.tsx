/**
 * StableGalleryImage - Image component with global load state
 *
 * Issue #64: Images were scintillating during streaming because React re-rendered
 * them on every token. This component uses a global cache to remember which images
 * have already loaded, so they appear instantly on subsequent renders.
 *
 * IMPORTANT: Uses custom memo comparison that ignores onClick to prevent re-renders
 * when parent passes new function references.
 */
const StableGalleryImage = memo(
  ({ src, alt, onClick }: { src: string; alt: string; onClick: () => void }) => {
    // Check if already loaded from cache (instant display)
    const alreadyLoaded = isImageLoaded(src);
    const [loaded, setLoaded] = useState(alreadyLoaded);
    // Context subscription bypasses the custom comparator below, so the
    // accessible name still refreshes on a language switch.
    const { t } = useTranslation();

    const handleLoad = () => {
      markImageLoaded(src);
      setLoaded(true);
    };

    return (
      // Opening the lightbox is a real action: native <button> around the
      // image — Enter/Space and focus come from the platform (audit F013).
      <button
        type="button"
        onClick={onClick}
        aria-label={t('common.expand_image')}
        className="inline-block align-top p-0 border-0 bg-transparent cursor-pointer rounded focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"
      >
        {/* eslint-disable-next-line @next/next/no-img-element -- External dynamic URL (Google Contacts photos), needs onLoad callback for cache */}
        <img
          src={proxyGoogleImageUrl(src) || src}
          alt={alt}
          className="contact-photo"
          referrerPolicy="no-referrer"
          style={{
            // Only keep opacity for loading animation - all other styles handled by CSS class
            opacity: loaded ? 1 : 0,
          }}
          onLoad={handleLoad}
        />
      </button>
    );
  },
  (prevProps, nextProps) => {
    // Only re-render if src or alt changes - ignore onClick function reference changes
    return prevProps.src === nextProps.src && prevProps.alt === nextProps.alt;
  }
);
StableGalleryImage.displayName = 'StableGalleryImage';

/**
 * Global cache for extracted gallery images.
 * Key: stringified image sources, Value: array of image data
 * This prevents re-extraction during streaming when the same images are present.
 */
const galleryImagesCache = new Map<string, Array<{ src: string; alt: string }>>();

/**
 * ContactPhotoGallery - Renders horizontal photo gallery with lightbox
 *
 * This component intercepts the HTML photo gallery generated by response_node.py
 * and adds interactive lightbox functionality to each photo.
 *
 * The backend generates:
 *   <div class="contact-photos-gallery">
 *     <img src="..." alt="Photo de {name}" class="contact-photo" />
 *     <img src="..." alt="Photo de {name}" class="contact-photo" />
 *   </div>
 *
 * This component enhances it with:
 * - Click to open lightbox
 * - Keyboard navigation (TODO: arrows for gallery)
 * - Proper responsive sizing
 * - Cached image extraction to prevent flicker during streaming
 */
const ContactPhotoGallery = ({ children }: { children?: React.ReactNode }) => {
  const [lightboxSrc, setLightboxSrc] = useState<string | null>(null);
  const [lightboxAlt, setLightboxAlt] = useState<string>('');

  // Extract images from children
  const extractImages = (node: React.ReactNode): Array<{ src: string; alt: string }> => {
    const images: Array<{ src: string; alt: string }> = [];

    const extract = (n: React.ReactNode) => {
      React.Children.forEach(n, child => {
        if (React.isValidElement(child)) {
          const childProps = child.props as {
            src?: string;
            alt?: string;
            children?: React.ReactNode;
          };
          if (child.type === 'img') {
            if (childProps.src) {
              images.push({ src: childProps.src, alt: childProps.alt || '' });
            }
          } else if (childProps.children) {
            extract(childProps.children);
          } else if (childProps.src && typeof childProps.src === 'string') {
            images.push({ src: childProps.src, alt: childProps.alt || '' });
          }
        }
      });
    };

    extract(node);
    return images;
  };

  // Extract current images
  const currentImages = extractImages(children);

  // Create cache key from image sources
  const cacheKey = currentImages
    .map(img => img.src)
    .sort()
    .join('|');

  // Use cached images if available (prevents flicker during streaming)
  // Only update cache if we have new images
  if (cacheKey && !galleryImagesCache.has(cacheKey)) {
    galleryImagesCache.set(cacheKey, currentImages);
  }

  const imagesToRender = galleryImagesCache.get(cacheKey) || currentImages;

  return (
    <>
      <div className="contact-photos-gallery">
        {imagesToRender.map(img => (
          <StableGalleryImage
            key={img.src}
            src={img.src}
            alt={img.alt}
            onClick={() => {
              setLightboxSrc(img.src);
              setLightboxAlt(img.alt);
            }}
          />
        ))}
      </div>
      {lightboxSrc && (
        <ImageLightbox
          src={lightboxSrc}
          alt={lightboxAlt}
          isOpen={!!lightboxSrc}
          onClose={() => setLightboxSrc(null)}
          minWidth={192}
        />
      )}
    </>
  );
};

/**
 * PlacePhotoWrapper - Wrapper for place photos with inline carousel
 *
 * When multiple photos are available (data-photo-urls attribute), displays
 * an inline carousel directly within the place card photo area.
 * The carousel has the same dimensions as the original photo.
 *
 * Fallback: If no data-photo-urls attribute is present (e.g., cached messages),
 * renders the original photo as-is.
 */
const PlacePhotoWrapper = ({
  children,
  ...props
}: {
  children?: React.ReactNode;
  [key: string]: unknown;
}) => {
  const { t } = useTranslation();

  // Parse data-photo-urls (JSON array of URLs)
  const photoUrlsJson = props['data-photo-urls'] as string | undefined;
  const photoUrls = useMemo(() => {
    if (!photoUrlsJson) return [];
    try {
      return JSON.parse(photoUrlsJson) as string[];
    } catch (error) {
      logger.warn('place_photo_urls_parse_failed', {
        component: 'PlacePhotoWrapper',
        error: error instanceof Error ? error.message : String(error),
      });
      return [];
    }
  }, [photoUrlsJson]);

  const hasMultiplePhotos = photoUrls.length > 1;

  // If multiple photos available, show inline carousel
  if (hasMultiplePhotos) {
    return (
      <div className="lia-place__photo">
        <InlinePlaceCarousel images={photoUrls} alt={t('gallery.place_photo')} />
      </div>
    );
  }

  // Single photo or no gallery data - render original content
  return <div className="lia-place__photo">{children}</div>;
};


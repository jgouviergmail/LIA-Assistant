"""Golden net + read-path guard for ``build_heartbeat_health_signals``.

The builder had **no test at all** before v1.25.18 — which is precisely how it
grew to issue six queries and ship ~30 000 raw sample rows per heartbeat tick
for a payload of a few dozen numbers. Two independent nets are pinned here:

1. **Payload golden** — the exact dict for eight datasets, generated by running
   the pre-extraction implementation (the builder still lived on
   ``HealthMetricsService`` and re-fetched through
   ``compute_kind_baseline_delta`` / ``detect_all_variations``). It must pass
   unchanged now that the builder is a module function fetching one per-day
   rollup per kind and reusing it.

2. **Read-path guard** — the exact number and shape of repository calls. A
   payload golden alone cannot see a regression that recomputes the same window
   twice: the output stays identical, only the cost explodes. That is the exact
   defect this work fixed, so it gets its own assertion rather than a comment.

Branch coverage of the case table (counted at generation time): the ``None``
return (no data at all), ``summary_today`` present/absent per kind, the 24-hour
freshness cutoff (``stale_only`` has a baseline but nothing fresh — proving
``any_data`` and ``baseline_deltas`` are independent gates), a fresh series with
no history (summary present, baseline ``empty``), single-kind and both-kind
payloads, a notable falling variation, and a steps inactivity streak.

Fixture clock: samples are placed at 09:00 UTC of their day, before the frozen
11:00 clock, so a ``days_ago=0`` entry IS visible — unlike the baseline
characterization net, where the same-day entries deliberately fall after
``now``.
"""


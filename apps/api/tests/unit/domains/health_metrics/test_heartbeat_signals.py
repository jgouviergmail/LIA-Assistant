@pytest.mark.parametrize("case_name", sorted(BUILDER_CASES), ids=sorted(BUILDER_CASES))
async def test_payload_is_pinned(case_name: str, monkeypatch: pytest.MonkeyPatch) -> None:
    """Payload must be byte-identical to the pre-extraction implementation."""
    _install_repo(monkeypatch, _make_samples(BUILDER_CASES[case_name]))

    payload = await build_heartbeat_health_signals(MagicMock(), USER_ID)

    assert repr(payload) == EXPECTED_PAYLOAD[case_name]


def test_golden_table_covers_every_case() -> None:
    """Guard against silent shrinkage of the case table."""
    assert set(EXPECTED_PAYLOAD) == set(BUILDER_CASES)


def test_golden_table_is_not_vacuous() -> None:
    """A table of empty payloads would survive any regression."""
    blob = "".join(EXPECTED_PAYLOAD.values())
    assert EXPECTED_PAYLOAD["no_data"] == "None"
    assert "'last_update_minutes_ago'" in blob
    assert "'baseline_deltas_7d': {'heart_rate'" in blob
    assert "'trend'" in blob
    assert "'event': 'inactivity_streak'" in blob



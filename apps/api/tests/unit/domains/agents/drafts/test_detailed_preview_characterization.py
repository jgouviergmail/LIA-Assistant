class TestOneVocabulary:
    """The rule the golden table encodes case by case, stated as a property.

    A table proves what it lists; a property covers the next renderer somebody
    writes. Both are wanted here — the old vocabulary leaked from 78 separate
    f-strings, and any one of them coming back would be invisible in a diff.
    """

    @staticmethod
    def _breaks_in_the_data(content: dict[str, Any]) -> int:
        """How many ``<br/>`` the CONTENT itself carries.

        A mail client writes them, and they travel in the body of a draft the
        person is confirming. What the renderer must never do is ADD one.
        """
        return json.dumps(content, ensure_ascii=False, default=str).count("<br/>")

    @pytest.mark.parametrize("case", CASES, ids=lambda case: case.case_id)
    def test_the_renderer_adds_no_html_break(self, case: PreviewCase) -> None:
        rendered = Draft(type=case.draft_type, content=case.content).get_detailed_preview(
            case.language, case.timezone
        )

        assert rendered.count("<br/>") <= self._breaks_in_the_data(case.content)

    @pytest.mark.parametrize("case", CASES, ids=lambda case: case.case_id)
    def test_nothing_opens_or_closes_on_blank_space(self, case: PreviewCase) -> None:
        # Every preview used to START with a break: the card opened on an empty
        # line, under a header that already stood on its own.
        rendered = Draft(type=case.draft_type, content=case.content).get_detailed_preview(
            case.language, case.timezone
        )

        assert rendered == rendered.strip()

    @pytest.mark.parametrize("case", CASES, ids=lambda case: case.case_id)
    def test_no_field_is_shown_with_nothing_in_it(self, case: PreviewCase) -> None:
        """« Début : » over nothing states less than saying nothing at all."""
        rendered = Draft(type=case.draft_type, content=case.content).get_detailed_preview(
            case.language, case.timezone
        )
        separator = get_draft_preview_labels(case.language)["separator"].rstrip()

        valueless = [
            line
            for line in rendered.splitlines()
            if line.rstrip() in {"-", "-" + separator} or line.rstrip().endswith(separator)
        ]
        assert not valueless, valueless



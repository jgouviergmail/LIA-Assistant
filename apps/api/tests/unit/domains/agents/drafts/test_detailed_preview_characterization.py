"""Golden characterization net for ``Draft.get_detailed_preview`` (extraction #2).

Pins the EXACT output string (byte-identical equality) of
``Draft.get_detailed_preview`` for a representative set of drafts covering
every ``DraftType`` value and every rendering branch, BEFORE the renderer is
extracted from ``drafts/models.py`` to a dedicated presentation module
(``drafts/preview_renderer.py``). Method: characterization-first decomposition
(Feathers), as applied by ADR-122 for the voice/TTS extraction — the net must
pass identically, unmodified, after the extraction.

The confirmation surfaces render this string verbatim, so the contract is
byte-identical output — assertions are full-string equality against the
``EXPECTED`` golden table (generated by running the implementation, never
written by hand), never substring checks. The table is regenerated ONLY on a
deliberate, reviewed behavior change, with the old/new tables diffed to prove
the change is surgical.

Two regenerations so far: the 2026-07-11 fallback fixes (localized
``no_subject``, ``None`` body, reminder ``"?"``), and ADR-276 lot 13, where
the vocabulary itself changed from HTML to Markdown — all 85 cases, each
diffed. A net that pins EVERY case is what makes such a change reviewable
rather than merely tested: the diff IS the change.

Branch coverage encoded in the case table:
- Email send/reply/forward shared branch: cc/bcc present and absent, forward
  attachments with ``filename`` key, ``name`` fallback, and ``"?"`` fallback.
- Email delete: ``from`` key vs ``from_addr`` fallback, date present/absent,
  and the localized ``no_subject`` fallback for a missing or empty subject
  (fixed 2026-07-11 — was a hardcoded French ``"(sans objet)"``).
- Reminder delete: full, partial, and fully-empty content (``"?"`` fallback
  line, consistent with the other delete types — fixed 2026-07-11).
- Event create/update/delete: timed vs all-day (``dateTime`` vs ``date``),
  modified-field ``✏️`` marks vs values preserved from ``current_event``,
  attendee ``email`` vs ``displayName`` fallback, empty content.
- Contact create/update/delete: modified marks vs ``current_contact``
  fallbacks, empty ``names`` list rendering ``"?"``.
- Task create/update/delete: due/notes present/absent, marks vs
  ``current_task`` fallbacks.
- File delete: ``mimeType`` present/absent, missing file dict.
- Label delete: ``children_only`` mode, 0 / few / more-than-5 sublabels
  (``... (+N)`` truncation), sublabel ``name`` fallback to ``"?"``.
- Forward body ``None``: shows NO message block at all (2026-07-11 it stopped
  rendering the literal string ``"None"``; lot 13 stopped heading an empty
  block, since a label above emptiness states less than silence).
- All 6 supported languages on the email branch, zh-CN datetime formatting,
  timezone conversion (Europe/Paris vs America/New_York), and the default
  argument binding (fr + DEFAULT_USER_DISPLAY_TIMEZONE).
- Unknown draft type: fallback to ``get_summary`` → ``"Draft (<value>)"``.
- MIXED cases (one field modified, the others preserved/absent) on every
  update type and on multi-optional create types: all-new/all-preserved pairs
  alone would let condition cross-wiring (e.g. the ✏️ mark of one field driven
  by another field's presence) pass undetected through the extraction.
"""


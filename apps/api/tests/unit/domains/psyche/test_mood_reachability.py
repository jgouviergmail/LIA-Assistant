def _replay_ordinary_regime(dominance_center: float) -> list[str]:
    """Replay the scripted stream through the real engine, service-faithfully.

    Mirrors the per-turn order of PsycheService.process_pre_response +
    process_post_response: decay -> circadian -> quadrant tracking -> proactive
    pulses -> appraisal (with relaxation) -> relationship/drives updates.

    Args:
        dominance_center: Translation under test (0.0 = today's default).

    Returns:
        Sequence of mood labels, one per turn.
    """
    baseline = PsycheEngine.compute_pad_baseline(
        _CYNIC,
        damping=PSYCHE_BASELINE_DAMPING_DEFAULT,
        dominance_center=dominance_center,
    )
    p, a, d = baseline.pleasure, baseline.arousal, baseline.dominance
    emotions: list[dict] = []
    now = datetime(2026, 7, 1, 9, 0, tzinfo=UTC)
    quadrant_since = now
    last_interaction: datetime | None = None
    last_appraisal: dict | None = None
    depth, warmth, trust, count = 0.0, 0.5, 0.3, 0
    stage = "ORIENTATION"
    curiosity, engagement = 0.5, 0.5
    tz_hour = 14.0
    labels: list[str] = []

    for dt_hours, emos, valence, quality in _ORDINARY_STREAM:
        now = now + timedelta(hours=dt_hours)
        tz_hour = (tz_hour + dt_hours) % 24.0

        pre_quadrant = PADVector(p, a, d).quadrant_key()
        p, a, d, emotions, warmth = PsycheEngine.apply_temporal_decay(
            mood_p=p,
            mood_a=a,
            mood_d=d,
            baseline=baseline,
            hours_elapsed=dt_hours,
            decay_rate=_EFFECTIVE_DECAY,
            emotions=emotions,
            emotion_decay_rate=0.4,
            warmth=warmth,
            warmth_decay_rate=0.02,
            has_interaction=True,
            traits=_CYNIC,
        )
        p = PsycheEngine.apply_circadian(p, tz_hour, 0.08)
        if PADVector(p, a, d).quadrant_key() != pre_quadrant:
            quadrant_since = now

        proactive = PsycheEngine.compute_proactive_emotions(
            drive_curiosity=curiosity,
            drive_engagement=engagement,
            interaction_count=count,
            last_appraisal=last_appraisal,
            self_efficacy=None,
            existing_emotions=emotions,
            now_iso=now.isoformat(),
        )
        if proactive:
            emotions = PsycheEngine.merge_proactive_emotions(emotions, proactive)

        inertia = PsycheEngine.compute_emotional_inertia(quadrant_since, now)
        appraisal = PsycheAppraisal(
            valence=valence, arousal=0.4, emotions=list(emos), quality=quality
        )
        p, a, d, emotions = PsycheEngine.apply_appraisal(
            mood_p=p,
            mood_a=a,
            mood_d=d,
            emotions=emotions,
            appraisal=appraisal,
            sensitivity=_EFFECTIVE_SENSITIVITY,
            inertia=inertia,
            max_active=4,
            now_iso=now.isoformat(),
            traits=_CYNIC,
            baseline=baseline,
            relaxation=0.15,
        )
        label = PsycheEngine.classify_mood(p, a, d)
        labels.append(label)
        last_appraisal = {"quality": quality, "emotion": appraisal.dominant_emotion}

        gap_hours = 0.0
        if last_interaction is not None:
            gap_hours = max(0.0, (now - last_interaction).total_seconds() / 3600.0)
        depth, warmth, trust, count, stage, reunion = PsycheEngine.update_relationship(
            depth=depth,
            warmth=warmth,
            trust=trust,
            interaction_count=count,
            stage=stage,
            quality=quality,
            gap_hours=gap_hours,
            now_iso=now.isoformat(),
        )
        if reunion:
            emotions = [*emotions, *reunion]
        curiosity, engagement = PsycheEngine.update_drives(curiosity, engagement, 0.4, quality)
        last_interaction = now

    return labels


class TestReachabilityOracle:
    """End-to-end: the recentered frame unlocks moods the un-recentered one cannot."""

    def test_uncentered_frame_stays_locked(self) -> None:
        """At center=0.0 the ordinary regime visits few moods (the measured lock).

        0.0 was the shipped default until the 2026-08-29 promotion; it stays
        pinned here as the counterfactual the recentering is measured against.
        """
        labels = _replay_ordinary_regime(dominance_center=0.0)
        assert len(set(labels)) <= 4, (
            f"unexpected variety without recentering: {sorted(set(labels))} — the "
            "confinement defect may have been fixed elsewhere; re-evaluate ADR-142"
        )

    def test_recommended_center_unlocks_variety(self) -> None:
        """At center=0.20 strictly more moods are reachable, monopoly broken."""
        locked = _replay_ordinary_regime(dominance_center=0.0)
        unlocked = _replay_ordinary_regime(dominance_center=RECOMMENDED_CENTER)
        assert len(set(unlocked)) > len(set(locked)), (
            f"recentering added no variety: {sorted(set(locked))} -> " f"{sorted(set(unlocked))}"
        )
        assert len(set(unlocked)) >= 5, f"expected >=5 moods, got {sorted(set(unlocked))}"
        top_share = max(unlocked.count(m) for m in set(unlocked)) / len(unlocked)
        assert top_share <= 0.70, f"one mood still holds {top_share:.0%} of turns"

    def test_replay_is_deterministic(self) -> None:
        """The oracle is stable: two replays produce identical label sequences."""
        assert _replay_ordinary_regime(0.0) == _replay_ordinary_regime(0.0)

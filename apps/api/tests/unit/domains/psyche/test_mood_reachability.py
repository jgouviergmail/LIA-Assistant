def _load_catalogue() -> list[tuple[str, PersonalityTraits, PADOverride | None]]:
    """Load the 14-personality catalogue from the seeding migration.

    Importing the module executes only its top-level statements (imports and
    the ``PERSONALITY_TRAITS`` literal) — ``upgrade()`` is never called.

    Returns:
        List of (personality_id, traits, optional PAD override).
    """
    spec = importlib.util.spec_from_file_location("psyche_traits_migration", _MIGRATION_PATH)
    assert spec is not None and spec.loader is not None, f"cannot load {_MIGRATION_PATH}"
    module = importlib.util.module_from_spec(spec)
    # Canonical importlib recipe: register before exec so anything resolving
    # the module via sys.modules (e.g. dataclasses) finds it.
    sys.modules["psyche_traits_migration"] = module
    spec.loader.exec_module(module)

    catalogue: list[tuple[str, PersonalityTraits, PADOverride | None]] = []
    for pid, o, c, e, a, n, pad_p, pad_a, pad_d in module.PERSONALITY_TRAITS:
        override = (
            PADOverride(pleasure=pad_p, arousal=pad_a, dominance=pad_d)
            if any(x is not None for x in (pad_p, pad_a, pad_d))
            else None
        )
        catalogue.append((str(pid), PersonalityTraits(o, c, e, a, n), override))
    return catalogue


def _resting(
    catalogue: list[tuple[str, PersonalityTraits, PADOverride | None]],
    dominance_center: float,
) -> dict[str, PADVector]:
    """Resting PAD baseline per personality id at the shipped damping."""
    return {
        pid: PsycheEngine.compute_pad_baseline(
            traits,
            override,
            damping=PSYCHE_BASELINE_DAMPING_DEFAULT,
            dominance_center=dominance_center,
        )
        for pid, traits, override in catalogue
    }



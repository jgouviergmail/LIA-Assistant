class TestCatalogueStraddle:
    """At the recommended activation value the catalogue must straddle D=0."""

    def test_straddles_zero(self) -> None:
        """>= 5 personalities rest on each side of D=0 at center 0.20."""
        resting = _resting(_load_catalogue(), dominance_center=RECOMMENDED_CENTER)
        below = sum(1 for pad in resting.values() if pad.dominance < 0.0)
        above = sum(1 for pad in resting.values() if pad.dominance > 0.0)
        assert below >= 5, f"only {below}/14 personalities rest D<0 — center too weak"
        assert above >= 5, f"only {above}/14 personalities rest D>0 — center too strong"

    def test_ordering_exactly_preserved(self) -> None:
        """The translation must not reorder personalities on the D axis."""
        catalogue = _load_catalogue()
        base = _resting(catalogue, dominance_center=0.0)
        centered = _resting(catalogue, dominance_center=RECOMMENDED_CENTER)
        ids = [pid for pid, _, _ in catalogue]
        order_base = sorted(ids, key=lambda i: base[i].dominance)
        order_centered = sorted(ids, key=lambda i: centered[i].dominance)
        assert order_base == order_centered

    def test_pleasure_and_arousal_untouched(self) -> None:
        """The translation is D-only: P and A resting points are identical."""
        catalogue = _load_catalogue()
        base = _resting(catalogue, dominance_center=0.0)
        centered = _resting(catalogue, dominance_center=RECOMMENDED_CENTER)
        for pid, _, _ in catalogue:
            assert centered[pid].pleasure == base[pid].pleasure
            assert centered[pid].arousal == base[pid].arousal



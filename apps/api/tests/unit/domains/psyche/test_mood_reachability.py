class TestGoldenNoOp:
    """The raw mapping stays frozen, and the shipped defaults stay the measured ones."""

    def test_shipped_defaults_are_the_activated_values(self) -> None:
        """Both knobs were promoted on 2026-08-29 after the production baseline.

        Shipped inert in v1.25.14 (0.0 / True) so the merge could be proven a
        no-op, then promoted once production data confirmed the diagnosis:
        D<0 share 0.0% over 769 snapshots, joy dominant 31-100% of turns.
        A change here is a product-policy change and needs an ADR entry.
        """
        assert PSYCHE_DOMINANCE_CENTER_DEFAULT == 0.20
        assert PSYCHE_PROACTIVE_JOY_PULSE_DEFAULT is False

    def test_shipped_default_delivers_the_straddle(self) -> None:
        """The promoted default must actually deliver the property it was promoted for."""
        resting = _resting(_load_catalogue(), dominance_center=PSYCHE_DOMINANCE_CENTER_DEFAULT)
        below = sum(1 for pad in resting.values() if pad.dominance < 0.0)
        above = sum(1 for pad in resting.values() if pad.dominance > 0.0)
        assert below >= 5 and above >= 5, (
            f"shipped default {PSYCHE_DOMINANCE_CENTER_DEFAULT} no longer straddles "
            f"D=0 ({below} below / {above} above) — re-derive it from the catalogue"
        )

    def test_catalogue_resting_points_match_goldens(self) -> None:
        """Resting PAD of all 14 personalities is frozen (abs tol 1e-9)."""
        catalogue = _load_catalogue()
        assert len(catalogue) == 14, "catalogue size changed — regenerate goldens + ADR"
        resting = _resting(catalogue, dominance_center=0.0)
        for pid, (gp, ga, gd) in _GOLDEN_RESTING.items():
            pad = resting[pid]
            assert pad.pleasure == pytest.approx(gp, abs=1e-9), (
                f"{pid}: pleasure {pad.pleasure} != golden {gp} — psyche baseline "
                "dynamics changed; if intended, regenerate goldens and justify in an ADR"
            )
            assert pad.arousal == pytest.approx(ga, abs=1e-9), f"{pid}: arousal drifted"
            assert pad.dominance == pytest.approx(gd, abs=1e-9), f"{pid}: dominance drifted"

    def test_todays_catalogue_rests_entirely_assertive(self) -> None:
        """Documents the measured defect: at center=0.0 NO personality rests D<0.

        This is the confinement ADR-142 addresses. If this test ever fails, the
        defect no longer exists in its measured form — re-evaluate whether the
        recentering knob is still needed before touching it.
        """
        resting = _resting(_load_catalogue(), dominance_center=0.0)
        assert all(pad.dominance > 0.0 for pad in resting.values())



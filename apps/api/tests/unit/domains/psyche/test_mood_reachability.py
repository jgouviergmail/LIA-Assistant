# Effective rates mirroring service defaults: user stability 60 -> decay x0.8,
# user sensitivity 70 -> appraisal sensitivity 0.7 * (0.15 + 1.85*0.7) ~= 1.01.
_EFFECTIVE_DECAY = 0.1 * 0.8
_EFFECTIVE_SENSITIVITY = 0.7 * (0.15 + 1.85 * 0.7)

# Ordinary-regime stream: 5 sessions x 6 messages (bursts 3 min apart, 16 h

"""Mood-reachability CI guards for the Psyche Engine (ADR-142).

Three guard families that turn the desired psyche properties into permanently
verified rules instead of hand-tuned numbers:

1. Golden characterization — the resting PAD of the 14 catalogue personalities
   under the RAW mapping (damping only, center pinned to 0.0) is frozen as
   literals. Any change to the baseline dynamics (Mehrabian coefficients,
   damping semantics, override blend) breaks this test loudly. A companion
   test pins the shipped defaults, which were promoted to the activated values
   on 2026-08-29 after the production baseline.
2. Catalogue-straddle guard — at the activation center (0.20, now the shipped
   default) the catalogue must straddle D=0 with the personality ordering
   exactly preserved. Protects the decision against future personality or
   coefficient edits.
3. Reachability oracle — a fixed ordinary-regime conversation replayed through
   the real engine: the un-recentered frame (center=0.0) keeps the mood locked
   in few labels; the recentered frame unlocks strictly more moods and breaks
   the single-mood monopoly. This is the end-to-end oracle ADR-068/ADR-104
   never had.

The personality catalogue is loaded from the seeding migration via importlib —
single source of truth, no duplicated table (Systemic Rules: registries).

Pure engine, no LLM, no DB. The appraisal stream is scripted; production
magnitudes are measured separately by ``apps/api/scripts/measure_psyche.py``.
"""


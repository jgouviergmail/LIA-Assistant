logger = structlog.get_logger(__name__)

#: The text generation's lease: renewed while the two model calls run.
TEXT_LEASE_SECONDS = 30
#: A waiter looks for the published text this often while the holder generates.
TEXT_POLL_SECONDS = 0.25

_CARDS_ROUTE = "briefing_cards"
_TEXT_ROUTE = "briefing_text"

TextState = Literal["ready", "uncertain", "sms_stale"]


class BriefingContextChanged(Exception):
    """The act expired, or its context changed: the client starts a new load."""


def _context_digest(service: BriefingService, now: datetime) -> str:
    return briefing_context_digest(
        hidden=service.hidden_sections,
        language=service.language,
        timezone=str(service.user_tz),
        local_day=now.astimezone(service.user_tz).date(),
    )


def _act_run_id(service: BriefingService, act: str, now: datetime) -> str:
    """The run a request of an act files under.

    Raises:
        BriefingContextChanged: The act expired or its context changed.
    """
    verdict = verify_act(
        act, user_id=service.user.id, context_digest=_context_digest(service, now), now=now
    )
    if verdict.check in ("expired", "context_changed"):
        raise BriefingContextChanged(verdict.check)
    if verdict.act_id is not None:
        return verdict.act_id
    # Foreign or unreadable: never honoured, never refused — a fresh act of the caller's own.
    logger.info("briefing_act_not_honoured", check=verdict.check)
    return new_act_id()


async def initial_cards(service: BriefingService, *, now: datetime) -> BriefingInitialResponse:
    """Every section that needs no slow source, the others pending; the act signed.

    Args:
        service: The caller's briefing service.
        now: The current instant (aware).

    Returns:
        The initial response.
    """
    started = time.perf_counter()
    act_id = new_act_id()
    service.consult_as(act_id)
    plans = {plan.name: plan for plan in service.plans()}

    async def first_look(name: str) -> CardSection:
        plan = plans[name]
        if name in service.hidden_sections or not plan.cache_eligible:
            return await service.read_plan(plan)
        cached = await service.cached_section(name)
        return cached or CardSection(status=CardStatus.PENDING, generated_at=now)

    async with (
        consultation_collector(act_id) as consulted,
        out_of_turn_spend(act_id, service.user.id, _CARDS_ROUTE),
    ):
        sections = await asyncio.gather(*(first_look(name) for name in plans))
    if consulted:
        await file_briefing_act(
            user_id=service.user.id, run_id=act_id, route=_CARDS_ROUTE, once=True
        )
    named = dict(zip(plans, sections, strict=True))
    # The text reads what this page showed when the cache let it go meanwhile (review B2).
    await keep_served(user_id=service.user.id, act_id=act_id, sections=named)
    expires_at = now + timedelta(seconds=settings.briefing_act_token_ttl_seconds)
    _timed("initial", started)
    return BriefingInitialResponse(
        cards=await revalidate_sms_card(CardsBundle(**named)),
        pending=[name for name, section in named.items() if section.status is CardStatus.PENDING],
        windows=build_briefing_windows(),
        act=sign_act(
            act_id=act_id,
            user_id=service.user.id,
            context_digest=_context_digest(service, now),
            expires_at=expires_at,
        ),
        act_expires_at=expires_at,
        section_concurrency=settings.briefing_section_concurrency,
    )


async def act_section(
    service: BriefingService, name: str, *, act: str, now: datetime
) -> CardSection:
    """Exactly one section of the act, read once across the workers.

    Args:
        service: The caller's briefing service.
        name: A section name (the router checked it).
        act: The token of the initial response.
        now: The current instant (aware).

    Returns:
        The section.

    Raises:
        BriefingContextChanged: The act expired or its context changed.
    """
    return await _read_one(service, name, run_id=_act_run_id(service, act, now), force=False)


async def refresh_section(service: BriefingService, name: str) -> CardSection:
    """One section re-read now (forced), as an act of its own.

    Args:
        service: The caller's briefing service.
        name: A section name (the router checked it).

    Returns:
        The section.
    """
    briefing_refresh_requests_total.labels(scope="single").inc()
    return await _read_one(service, name, run_id=new_act_id(), force=True)


async def _read_one(
    service: BriefingService, name: str, *, run_id: str, force: bool
) -> CardSection:
    started = time.perf_counter()
    service.consult_as(run_id)
    plan = {p.name: p for p in service.plans(frozenset({name}) if force else frozenset())}[name]
    async with (
        consultation_collector(run_id) as consulted,
        out_of_turn_spend(run_id, service.user.id, _CARDS_ROUTE),
    ):
        if force or name in service.hidden_sections or not plan.cache_eligible:
            section = await service.read_plan(plan)
        else:
            section = await _shared_section(service, name, lambda: service.read_plan(plan))
    if consulted:
        await file_briefing_act(
            user_id=service.user.id, run_id=run_id, route=_CARDS_ROUTE, once=True
        )
    _timed("refresh" if force else "section", started)
    return await revalidate_sms_section(section) if name == SECTION_SMS else section


async def _shared_section(
    service: BriefingService, name: str, build: Callable[[], Awaitable[CardSection]]
) -> CardSection:
    """One live read of a section across the workers; the others take what it published."""
    hidden = ",".join(sorted(service.hidden_sections))
    shared = await run_shared_flight(
        f"{CLAIM_PREFIX}:briefing_section:{service.user.id}"
        f":{service.language}:{service.user_tz}:{hidden}:{name}",
        build=build,
        read_shared=lambda: service.cached_section(name),
        read_settled=lambda: service.cached_section(name, settled=True),
        wait_budget_s=settings.briefing_shared_build_max_wait_seconds,
        owner_liveness=True,
    )
    return shared.value


async def act_text(
    service: BriefingService, *, act: str, force: bool, now: datetime
) -> BriefingTextResponse:
    """The greeting and synthesis of the act's settled sections, generated once per input.

    Args:
        service: The caller's briefing service.
        act: The token of the initial response.
        force: Bypass a text already generated for these inputs.
        now: The current instant (aware).

    Returns:
        The text, whether it was reused, and its state.

    Raises:
        BriefingContextChanged: The act expired or its context changed.
    """
    started = time.perf_counter()
    run_id = _act_run_id(service, act, now)
    service.consult_as(run_id)
    async with consultation_collector(run_id) as consulted:
        cards = await service.settled_bundle(
            served=await served_sections(user_id=service.user.id, act_id=run_id)
        )
        prompt_sms = await read_prompt_sms(service.user.id, cards.sms)
        key = await _text_key(service, cards, prompt_sms, now)
        # « 0 disables »: nothing read, kept or waited for — each request generates its
        # own text (a waiter used to find nothing published and answer uncertain).
        kept = settings.briefing_text_cache_ttl_seconds > 0
        cached = await read_text(key) if kept and not force else None
        response = (
            _response(cached, reused=True, state="ready")
            if cached is not None
            else await (
                _generate_once(service, cards, prompt_sms, key)
                if kept
                else _generate(service, cards, prompt_sms, key)
            )
        )
    if consulted:
        await file_briefing_act(
            user_id=service.user.id, run_id=run_id, route=_TEXT_ROUTE, once=True
        )
    _timed("text", started)
    return response


def _timed(step: str, started: float) -> None:
    """Observe one step of an act (``briefing_act_step_duration_seconds``)."""
    briefing_act_step_duration_seconds.labels(step=step).observe(time.perf_counter() - started)


async def _text_key(
    service: BriefingService, cards: CardsBundle, prompt_sms: PromptSms, now: datetime
) -> str:
    projected, statuses = project_cards(cards)
    signal = prompt_sms.signal
    fingerprint = text_fingerprint(
        projected,
        statuses,
        build_briefing_windows(),
        get_llm_config_for_agent(settings, BRIEFING_LLM_TYPE).model_dump_json(),
        f"{settings.briefing_greeting_prompt_version}/{settings.briefing_synthesis_prompt_version}",
        f"{signal.revision}:{signal.stamp}" if signal is not None else None,
        local_hour=local_hour(now.astimezone(service.user_tz)),
        person=await person_inputs_digest(service.user),
    )
    return text_cache_key(
        user_id=service.user.id, language=service.language, fingerprint=fingerprint
    )


async def _generate_once(
    service: BriefingService, cards: CardsBundle, prompt_sms: PromptSms, key: str
) -> BriefingTextResponse:
    """Generate under a lease the workers share; a lost lease is never relaunched."""
    claim = f"{CLAIM_PREFIX}:briefing_text:{service.user.id}:{key.rsplit(':', 1)[-1]}"
    token = uuid.uuid4().hex
    try:
        redis = await get_redis_cache()
        claimed = await try_claim(redis, claim, token, ttl_seconds=TEXT_LEASE_SECONDS)
    except Exception as exc:  # noqa: BLE001 - without the cache, nothing can be shared
        logger.debug("briefing_text_claim_unavailable", error_type=type(exc).__name__)
        return await _generate(service, cards, prompt_sms, key)
    if not claimed:
        return await _published_or_uncertain(service, redis, claim, key)
    try:
        # ``held_claim`` renews the lease while the model calls run and releases it by its token.
        async with held_claim(redis, claim, token, ttl_seconds=TEXT_LEASE_SECONDS):
            return await _generate(service, cards, prompt_sms, key)
    except ClaimLost as lost:
        logger.info("briefing_text_lease_lost", reason=lost.reason)
        return _uncertain(service)


async def _generate(
    service: BriefingService, cards: CardsBundle, prompt_sms: PromptSms, key: str
) -> BriefingTextResponse:
    text = await service.compose_text(cards, prompt_sms)
    if prompt_sms.signal is not None and not await sms_signal_current(prompt_sms.signal):
        return _response(text, reused=False, state="sms_stale")
    if _keepable(text, cards, prompt_sms):
        await write_text(key, text)
    return _response(text, reused=False, state="ready")


def _keepable(text: SynthesisResponse, cards: CardsBundle, prompt_sms: PromptSms) -> bool:
    """Only what the model wrote is kept: a written fallback stands for a failure or a refusal.

    The greeting is a model answer when it carries its usage; a missing
    synthesis is a model outcome only when the bundle was too sparse to ask for
    one (``synthesis_expected``, the synthesis' own rule).
    """
    if text.greeting.usage is None:
        return False
    return text.synthesis is not None or not synthesis_expected(cards, prompt_sms)


async def _published_or_uncertain(
    service: BriefingService, redis: Any, claim: str, key: str
) -> BriefingTextResponse:
    """Wait for the holder's text; its lease gone without one is uncertain, never relaunched."""
    loop = asyncio.get_running_loop()
    deadline = loop.time() + settings.briefing_shared_build_max_wait_seconds
    while loop.time() < deadline:
        published = await read_text(key)
        if published is not None:
            return _response(published, reused=True, state="ready")
        try:
            held = await redis.get(claim) is not None
        except Exception as exc:  # noqa: BLE001 - an unreadable claim decides nothing
            logger.debug("briefing_text_claim_unreadable", error_type=type(exc).__name__)
            held = True
        if not held:
            published = await read_text(key)  # published just before the release
            return (
                _response(published, reused=True, state="ready")
                if published is not None
                else _uncertain(service)
            )
        await asyncio.sleep(TEXT_POLL_SECONDS)
    return _uncertain(service)


def _uncertain(service: BriefingService) -> BriefingTextResponse:
    """The written greeting: what the generation produced is unknown, and nothing relaunches it."""
    return BriefingTextResponse(
        greeting=TextSection(
            text=fallback_greeting(service.user, service.user_tz, service.language),
            generated_at=datetime.now(UTC),
        ),
        synthesis=None,
        reused=False,
        state="uncertain",
    )


def _response(text: SynthesisResponse, *, reused: bool, state: TextState) -> BriefingTextResponse:
    return BriefingTextResponse(
        greeting=text.greeting, synthesis=text.synthesis, reused=reused, state=state
    )



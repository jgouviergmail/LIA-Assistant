"""The progressive dashboard: what shows at once, then each slow section, then the text.

Spec 2026-10-21 §5.8 (D2). The dashboard used to wait for its slowest source:
one request built the whole bundle, and the text waited for that. Now one page
load is one ACT:

- ``initial_cards`` answers at once with every section it can serve without a
  slow source: hidden ones as placeholders, the local ones (reminders,
  workboard, SMS) read live, the cache-eligible ones from their cache or
  ``PENDING`` — never a live fetch of a slow source. It signs the act.
- ``act_section`` reads EXACTLY one section of the act, under a section-level
  claim shared by the workers (owner liveness); its consultations and spend
  are filed under the act's run id, its decision once per act.
- ``act_text`` reads caches and recent failures only — never a fetch of a
  slow source — and generates the greeting and synthesis once per distinct
  input (``text_cache``). A lost generation lease answers ``uncertain`` and
  relaunches nothing (Q3): what the model was sent, and billed, is unknown.
- ``refresh_section`` re-reads one section, forced, as an act of its own; the
  text is not regenerated by itself (its inputs changed, so its next request
  does).

A token for another account, or an unreadable one, is never honoured: the
request runs as a fresh act of its own, exact and attributed to the caller. An
expired act, or one whose context changed (language, timezone, local day,
hidden set), raises ``BriefingContextChanged`` — ``409
briefing_context_changed``: the client starts a new load.
"""


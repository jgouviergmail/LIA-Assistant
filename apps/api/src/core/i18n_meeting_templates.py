#: The catalogue keys, in library order — the oracle of the completeness asserts.
TEMPLATE_KEYS: tuple[str, ...] = tuple(_TEMPLATE_NAMES)

# Boot-time completeness (ADR-085): names and descriptions cover the same keys,
# every tuple carries the six languages.
assert set(_TEMPLATE_NAMES) == set(_TEMPLATE_DESCRIPTIONS), "template descriptions must cover names"
for _table in (_TEMPLATE_NAMES, _TEMPLATE_DESCRIPTIONS, _SECTION_LABELS):
    for _key, _values in _table.items():
        assert len(_values) == len(_LANGUAGES), f"{_key}: expected {len(_LANGUAGES)} languages"


def _index(language: str | None) -> int:
    """Position of the resolved language in every tuple (the chokepoint decides the fallback)."""
    code = normalize_language(language or "")
    return _LANGUAGES.index(code) if code in _LANGUAGES else _LANGUAGES.index(_DEFAULT)


def get_template_name(key: str, language: str | None) -> str:
    """Localized name of a built-in template."""
    return _TEMPLATE_NAMES[key][_index(language)]


def get_template_description(key: str, language: str | None) -> str:
    """Localized description of a built-in template."""
    return _TEMPLATE_DESCRIPTIONS[key][_index(language)]


def get_section_label(key: str, language: str | None) -> str:
    """Localized label of a section key any template may use."""
    return _SECTION_LABELS[key][_index(language)]


def section_label_keys() -> frozenset[str]:
    """Every section key that has a label (catalogue completeness oracle)."""
    return frozenset(_SECTION_LABELS)


def supported_languages() -> tuple[str, ...]:
    """Languages every table above covers (parity test oracle)."""
    return _LANGUAGES



def build(split: Split) -> tuple[Case, ...]:
    """The split's cases, in a stable order."""
    rows = CALIBRATION if split == "calibration" else INDEPENDENT
    return tuple(
        single(
            "d5",
            split,
            index,
            language,
            family,
            # The engines see the request, the parameter and the value — never the
            # turn's resolved values, which only the replay of the old guard reads.
            {"query": query, "parameter": PARAMETERS[parameter], "value": value},
            gold,
            resolved_values=list(resolved),
        )
        for index, (language, family, query, parameter, value, gold, resolved) in enumerate(rows, 1)
    )

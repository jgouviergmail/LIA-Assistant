SPLIT = "independent"


def build(decision: Decision) -> tuple[Case, ...]:
    """The version 2 independent cases of one decision (ids ``<decision>-iv2-NNN``)."""
    if decision == "d3":
        return tuple(
            Case(
                id=f"d3-iv2-{i:03d}",
                decision="d3",
                split=SPLIT,
                language=language,
                family=family,
                state={"query": query},
                gold=primary,
                accepted=frozenset({primary}) if primary else frozenset(),
                required=frozenset(required),
                optional=frozenset(acceptable),
            )
            for i, (language, family, query, required, acceptable, primary) in enumerate(D3, 1)
        )
    if decision == "d4":
        return tuple(
            Case(
                id=f"d4-iv2-{i:03d}",
                decision="d4",
                split=SPLIT,
                language=language,
                family=family,
                state={"query": query},
                required=frozenset(required),
                optional=frozenset(optional),
            )
            for i, (language, family, query, required, optional) in enumerate(D4, 1)
        )
    if decision == "d5":
        return tuple(
            Case(
                **{
                    **single(
                        "d5",
                        SPLIT,
                        i,
                        language,
                        family,
                        {
                            "query": query,
                            "parameter": corpus_d5.PARAMETERS[parameter],
                            "value": value,
                        },
                        gold,
                        resolved_values=list(resolved),
                        parameter_key=parameter,
                    ).__dict__,
                    "id": f"d5-iv2-{i:03d}",
                }
            )
            for i, (language, family, query, parameter, value, gold, resolved) in enumerate(D5, 1)
        )
    raise ValueError(f"no version 2 corpus for {decision}")

def _case(split: Split, index: int, row: Row) -> Case:
    language, family, query, required, acceptable, primary = row
    return Case(
        id=f"d3-{split[:3]}-{index:03d}",
        decision="d3",
        split=split,
        language=language,
        family=family,
        state={"query": query},
        gold=primary,
        accepted=frozenset({primary}) if primary else frozenset(),
        required=frozenset(required),
        optional=frozenset(acceptable),
    )


def build(split: Split) -> tuple[Case, ...]:
    """The split's cases; the independent split reads the existing taxonomy corpus."""
    if split == "calibration":
        return tuple(_case(split, i, row) for i, row in enumerate(CALIBRATION, 1))
    from scripts.semantic_simulation.taxonomy_corpus import TAXONOMY_CASES

    rows: list[Row] = [
        (
            "zh" if case.language.startswith("zh") else case.language,
            "multi" if len(case.required_domains) > 1 else "single",
            case.query,
            case.required_domains,
            case.acceptable_domains,
            case.expected_primary,
        )
        for case in TAXONOMY_CASES
        if case.menu_variant == "native"
    ]
    rows.append(("fr", "incident", INCIDENT_QUERY, ("weather", "place"), (), None))
    return tuple(_case(split, i, row) for i, row in enumerate(rows, 1))

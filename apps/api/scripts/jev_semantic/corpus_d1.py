def build(split: Split) -> tuple[Case, ...]:
    """The split's cases, in a stable order."""
    rows = CALIBRATION if split == "calibration" else INDEPENDENT
    return tuple(
        single(
            "d1",
            split,
            index,
            language,
            family,
            {"query": query, "reference": reference, "value": value},
            gold,
            also,
        )
        for index, (language, family, query, reference, value, gold, also) in enumerate(rows, 1)
    )

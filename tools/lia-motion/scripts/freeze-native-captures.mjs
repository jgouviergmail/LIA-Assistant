/** Freeze a complete native-footage inventory and retain its provenance. */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repo = path.resolve(project, '../..');
const root = path.join(project, 'public/capture-v2');
const manifestPath = path.join(root, 'manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const sha = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const components = {
  chat: ['components/chat/ChatInput.tsx', 'app/[lng]/dashboard/chat/page.tsx'],
  dossier: ['components/chat/ChatInput.tsx', 'app/[lng]/dashboard/chat/page.tsx'],
  approval: ['components/chat/HitlActionCard.tsx', 'hooks/usePendingHitlSync.ts'],
  knowledge: ['app/[lng]/dashboard/spaces/[id]/page.tsx'],
  skill: ['components/chat/SkillAppWidget.tsx'],
  relations: ['components/relations/RelationDetailPanel.tsx', 'components/relations/RelationCardList.tsx'],
  meetings: ['components/meetings/MeetingReportView.tsx', 'app/[lng]/dashboard/meetings/[id]/page.tsx'],
  workboard: ['components/workboard/WorkboardPage.tsx'],
  radio: ['components/radio/RadioPage.tsx', 'components/radio/RadioArticles.tsx'],
  briefing: ['components/dashboard/TodayBriefing.tsx'],
  memory: ['components/settings/MemorySettings.tsx'],
  routines: ['components/settings/ScheduledActionsSettings.tsx'],
  habits: ['components/settings/HabitsSettings.tsx'],
  journals: ['components/settings/JournalsSettings.tsx'],
  health: ['components/settings/HealthMetricsSettings.tsx'],
  peers: ['components/settings/PeerConnectionsSettings.tsx'],
  voice: ['components/settings/VoiceModeSettings.tsx'],
  connections: ['components/settings/UserConnectorsSection.tsx'],
  avatars: ['components/settings/EyesStyleSettings.tsx'],
  extensions: ['components/settings/SkillsSettings.tsx'],
  mcp: ['components/settings/MCPServersSettings.tsx'],
  administration: ['components/settings/AdminUsageLimitsSection.tsx'],
  plugins: ['components/settings/PluginsSettings.tsx'],
  live: ['components/settings/LiveModeSettings.tsx'],
  simli: ['components/settings/AvatarSettings.tsx'],
  images: ['components/settings/ImageGenerationSettings.tsx'],
  files: ['components/settings/GeneratedAssetsSettings.tsx', 'components/settings/generated-assets/GeneratedAssetGrid.tsx'],
  phone: ['components/settings/TelephonyCallsSection.tsx'],
  'phone-identity': ['components/settings/TelephonyIdentitySection.tsx'],
  agents: ['components/settings/AdminLLMConfigSection.tsx'],
  heartbeat: ['components/settings/HeartbeatSettings.tsx'],
  mobile: ['components/chat/ChatInput.tsx', 'app/[lng]/dashboard/chat/page.tsx'],
};
const sourcePaths = Object.fromEntries(Object.entries(components).map(([id, files]) => [id, files.map(file => `apps/web/src/${file}`)]));
for (const files of Object.values(sourcePaths)) for (const file of files) if (!fs.existsSync(path.join(repo, file))) throw new Error(`Missing native source ${file}`);
for (const asset of manifest.assets) {
  if (!asset.clipPath) throw new Error(`Unencoded asset ${asset.id}`);
  if (sha(path.join(project, 'public', asset.path)) !== asset.sha256 || sha(path.join(project, 'public', asset.clipPath)) !== asset.clipSha256) throw new Error(`Asset hash mismatch ${asset.id}`);
  asset.sourceComponents = sourcePaths[asset.id] ?? [];
  asset.nativeUrl = `http://127.0.0.1:3134${asset.route ?? asset.scene?.route ?? ''}`;
}
manifest.freeze = { frozenAt: new Date().toISOString(), reason: 'Capture extension stopped; inventory retained for directed workflow revision.', assetCount: manifest.assets.length, uniqueClipCount: new Set(manifest.assets.map(asset => asset.clipPath)).size, noFurtherAssetMutationsDuringRender: true };
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
const reportsRoot = path.join(repo, 'output/playwright/lia-motion-native-v2');
const campaigns = fs.readdirSync(reportsRoot).filter(file => /^capture-report-\d+\.json$/.test(file)).sort().map(file => {
  const result = JSON.parse(fs.readFileSync(path.join(reportsRoot, file), 'utf8'));
  return { reportArtifact: `output/playwright/lia-motion-native-v2/${file}`, captured: result.report.filter(item => !item.failed).map(item => item.id), failed: result.report.filter(item => item.failed).map(item => ({ id: item.id, reason: item.failed })), transportGuardBlocked: result.transportGuardBlocked };
});
const documents = fs.readdirSync(path.join(root, 'demo-files')).filter(file => file.endsWith('.pdf')).map(file => ({ path: `capture-v2/demo-files/${file}`, sha256: sha(path.join(root, 'demo-files', file)), provenance: 'Local fictional PDF fixture authored by scripts/create-capture-documents.py using ReportLab; not generated by LIA or a model provider.' }));
const provenance = {
  version: 1,
  freeze: manifest.freeze,
  manifestSha256: sha(manifestPath),
  nativeRuntime: manifest.capture.runtime,
  currentRepositoryRevision: manifest.capture.currentRepositoryRevision,
  exactCompiledRevisionEstablished: false,
  sourceComponentPathsAreCurrentRepositoryCorrespondence: true,
  captureMethod: 'Official Chromium and real isolated Next.js frontend. Fictional API responses; original native components, styles, interactions and avatars. No product DOM reconstruction.',
  networkBoundary: 'Repository api-network-guard proxy plus page API interception. Background requests shown below were blocked. No live backend/API/provider operation or private account data.',
  audioBoundary: 'Radio playback uses a local silent WAV solely to exercise its native controls. No generated speech, Live or Simli session. Clip audio removed during MP4 encoding.',
  fixtureSources: ['apps/web/e2e/capture/landing-proof-data.ts', 'apps/web/e2e/capture/public-screenshot-data.ts', 'apps/web/e2e/smoke/settings-habits.spec.ts', 'apps/web/e2e/smoke/settings-heartbeat.spec.ts', 'apps/web/e2e/smoke/generated-assets-gallery.spec.ts', 'tools/lia-motion/scripts/capture-native.mjs'],
  contractSources: ['apps/web/src/types/telephony.ts', 'apps/web/src/types/generated-assets.ts', 'apps/web/src/lib/avatars/types.ts', 'apps/web/src/lib/live/types.ts', 'apps/web/src/hooks/useHeartbeatSettings.ts', 'apps/web/src/hooks/useImageGenerationOptions.ts'],
  encoding: 'Raw Playwright video trimmed and reencoded H.264, 30 fps, yuv420p, CRF16. No substituted product pixels. Native desktop 1440x960; mobile independently captured 390x844.',
  assets: manifest.assets.map(({ clipRawPath, ...asset }) => asset),
  documents,
  campaigns,
};
fs.writeFileSync(path.join(root, 'provenance.json'), JSON.stringify(provenance, null, 2) + '\n');
console.log(JSON.stringify({ ...manifest.freeze, manifestSha256: provenance.manifestSha256 }));

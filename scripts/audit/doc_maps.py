def _display_width(text: str) -> int:
    """Columns a string takes, East Asian wide characters counting two (as Prettier does)."""
    return sum(2 if unicodedata.east_asian_width(ch) in ("W", "F") else 1 for ch in text)


def dump_json(value: object, width: int = 100) -> str:
    """Serialise JSON exactly as Prettier prints it, so ``pnpm format`` is a no-op on it.

    Objects are always expanded; an array of scalars stays on one line when the
    whole line — indentation, key and trailing comma included — fits ``width``.
    """

    def scalar(v: object) -> str:
        return json.dumps(v, ensure_ascii=False)

    def render(v: object, indent: int, used: int, tail: int) -> str:
        pad = "  " * indent
        if isinstance(v, dict):
            if not v:
                return "{}"
            keys = list(v)
            lines = []
            for i, k in enumerate(keys):
                head = f"{pad}  {scalar(k)}: "
                comma = "," if i < len(keys) - 1 else ""
                lines.append(
                    head + render(v[k], indent + 1, _display_width(head), len(comma)) + comma
                )
            return "{\n" + "\n".join(lines) + "\n" + pad + "}"
        if isinstance(v, list):
            if not v:
                return "[]"
            if all(not isinstance(x, (dict, list)) for x in v):
                flat = "[" + ", ".join(scalar(x) for x in v) + "]"
                if used + _display_width(flat) + tail <= width:
                    return flat
            items = []
            for i, x in enumerate(v):
                comma = "," if i < len(v) - 1 else ""
                items.append(f"{pad}  " + render(x, indent + 1, len(pad) + 2, len(comma)) + comma)
            return "[\n" + "\n".join(items) + "\n" + pad + "]"
        return scalar(v)

    return render(value, 0, 0, 0) + "\n"


def write_json(path: Path, value: object) -> None:
    """Write a data file in the one format every tool of the repository agrees on."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump_json(value), encoding="utf-8", newline="\n")



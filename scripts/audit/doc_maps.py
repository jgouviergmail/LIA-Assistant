@dataclass(frozen=True)
class Tree:
    """What exists in the repository, as a fresh clone would see it."""

    root: Path
    files: frozenset[str]
    dirs: frozenset[str]

    def exists(self, rel: str) -> bool:
        """Whether a repo-relative file or directory exists in the tree."""
        rel = rel.strip("/")
        return rel in self.files or rel in self.dirs


def load_tree(root: Path, include_unstaged: bool) -> Tree:
    """List tracked files (plus what ``git add -A`` would stage, on request)."""
    cmd = ["git", "ls-files", "-z"]
    names = (
        subprocess.run(cmd, cwd=root, capture_output=True, check=True)
        .stdout.decode("utf-8")
        .split("\0")
    )
    files = {n for n in names if n}
    if include_unstaged:
        extra = (
            subprocess.run(
                ["git", "ls-files", "-z", "--others", "--exclude-standard"],
                cwd=root,
                capture_output=True,
                check=True,
            )
            .stdout.decode("utf-8")
            .split("\0")
        )
        files |= {n for n in extra if n}
        files = {f for f in files if (root / f).exists()}
    dirs: set[str] = set()
    for f in files:
        parts = f.split("/")
        for i in range(1, len(parts)):
            dirs.add("/".join(parts[:i]))
    return Tree(root=root, files=frozenset(files), dirs=frozenset(dirs))


def children(tree: Tree, parent: str) -> set[str]:
    """Direct children (files and directories) of a tracked directory."""
    prefix = parent.rstrip("/") + "/"
    out: set[str] = set()
    for f in tree.files:
        if f.startswith(prefix):
            out.add(f[len(prefix) :].split("/", 1)[0])
    return out


def backend_domains(tree: Tree) -> list[str]:
    """Backend bounded contexts: the directories of ``apps/api/src/domains``."""
    base = "apps/api/src/domains"
    return sorted(
        c for c in children(tree, base) if f"{base}/{c}" in tree.dirs and not c.startswith("__")
    )


def infra_units(tree: Tree) -> list[str]:
    """Infrastructure modules: packages and top-level modules of ``src/infrastructure``."""
    base = "apps/api/src/infrastructure"
    out = set()
    for c in children(tree, base):
        if c.startswith("__"):
            continue
        if f"{base}/{c}" in tree.dirs:
            out.add(c)
        elif c.endswith(".py"):
            out.add(c[:-3])
    return sorted(out)


def adr_files(tree: Tree) -> dict[int, str]:
    """ADR number → file name, for every ADR file of ``docs/architecture``."""
    out: dict[int, str] = {}
    for f in tree.files:
        m = ADR_FILE_RE.match(f)
        if m:
            out[int(m.group(1))] = f.rsplit("/", 1)[1]
    return out


def site_languages(tree: Tree) -> list[str]:
    """The languages of the site — its locale catalogues — source language first."""
    found = {m.group(1) for f in tree.files if (m := LOCALE_FILE_RE.match(f))}
    return sorted(found, key=lambda lang: (lang != SOURCE_LANG, lang))


def repo_facts(tree: Tree) -> dict[str, object]:
    """Counts and dates the pages show, computed from the tree — never typed in the data."""
    root = tree.root
    version = json.loads((root / "package.json").read_text(encoding="utf-8"))["version"]
    releases = [
        (v, d) for v, d in RELEASE_RE.findall((root / "CHANGELOG.md").read_text(encoding="utf-8"))
    ]
    dates = dict(releases)
    milestones = sorted(
        ({"version": v, "date": d} for v, d in releases if v.endswith(".0") or v == version),
        key=lambda r: (r["date"], [int(x) for x in r["version"].split(".")]),
    )
    domains = backend_domains(tree)
    files = adr_files(tree)
    return {
        "version": version,
        "releaseDate": dates.get(version, ""),
        "releases": len(releases),
        "milestones": milestones,
        # The shared kernel is not a functional domain (the README counts the same way).
        "domains": len([d for d in domains if d != "shared"]),
        "infra": len(infra_units(tree)),
        "adrFiles": len(files),
    }


def site_facts(tree: Tree) -> dict[str, object]:
    """``facts.json``: what the site pages read from outside ``apps/web``."""
    facts = repo_facts(tree)
    names = {str(n): f for n, f in sorted(adr_files(tree).items())}
    return {**{k: v for k, v in facts.items() if k != "adrFiles"}, "adrFiles": names}



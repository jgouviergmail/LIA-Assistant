@dataclass(frozen=True)
class Maps:
    """The structure of the three maps, their text in every language, the vendored icons."""

    functional: dict
    technical: dict
    history: dict
    text: dict[str, dict[str, dict]]
    icons: dict[str, list]

    def structure(self, name: str) -> dict:
        """The structure document of one map."""
        return {
            "functional": self.functional,
            "technical": self.technical,
            "history": self.history,
        }[name]


def load_maps(data_dir: Path, icons_path: Path) -> Maps:
    """Read the structure, every text file and the vendored icons."""

    def read(path: Path) -> dict:
        return json.loads(path.read_text(encoding="utf-8"))

    text: dict[str, dict[str, dict]] = {}
    for path in sorted((data_dir / "text").glob("*.json")):
        m = TEXT_FILE_RE.match(path.name)
        if m:
            text.setdefault(m.group(2), {})[m.group(1)] = read(path)
    icons = read(icons_path) if icons_path.exists() else {}
    return Maps(
        read(data_dir / "functional.json"),
        read(data_dir / "technical.json"),
        read(data_dir / "history.json"),
        text,
        icons,
    )


def unit_ids(maps: Maps, name: str, section: str) -> list[str]:
    """The ids a text section must hold, in structure order (``intro`` holds none)."""
    doc = maps.structure(name)
    if section == "entries":
        return [str(e["adr"]) for e in doc.get("entries", [])]
    return [x["id"] for x in doc.get(section, [])]


def text_units(maps: Maps, lang: str) -> dict[str, dict | None]:
    """Every unit of a language, keyed ``map/section[/id]`` — None where it is absent."""
    out: dict[str, dict | None] = {}
    for name, sections in TEXT_SCHEMA.items():
        doc = maps.text.get(lang, {}).get(name, {})
        for section in sections:
            if section == "intro":
                out[f"{name}/intro"] = doc.get("intro")
                continue
            held = doc.get(section, {})
            for uid in unit_ids(maps, name, section):
                out[f"{name}/{section}/{uid}"] = held.get(uid)
    return out


def fingerprint(unit: dict) -> str:
    """Fingerprint of a SOURCE unit — what a translation declares it translated."""
    body = {k: v for k, v in unit.items() if k != FINGERPRINT}
    canonical = json.dumps(body, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()[:12]


def referenced_icons(maps: Maps) -> set[str]:
    """Every icon name the documents will draw."""
    names = set(CHROME_ICONS) | {p["icon"] for p in PAGES.values()}
    for key in ("groups", "bricks", "flows"):
        names |= {x["icon"] for x in maps.functional.get(key, [])}
    for key in ("layers", "bricks", "flows"):
        names |= {x["icon"] for x in maps.technical.get(key, [])}
    names |= {t["icon"] for t in maps.history.get("themes", [])}
    return names


def vendor_icons(root: Path, names: set[str]) -> tuple[dict[str, list], list[str]]:
    """Extract the geometry of the named Lucide icons from the installed package."""
    out: dict[str, list] = {}
    missing: list[str] = []
    for name in sorted(names):
        src = root / LUCIDE_DIR / f"{name}.mjs"
        if not src.exists():
            missing.append(name)
            continue
        text = src.read_text(encoding="utf-8")
        start = text.find("__iconNode = [")
        body = text[start : text.find("];", start)]
        nodes = []
        for tag, attrs in LUCIDE_NODE_RE.findall(body):
            kept = {k: v for k, v in LUCIDE_ATTR_RE.findall(attrs) if k != "key"}
            nodes.append([tag, kept])
        out[name] = nodes
    return out, missing



#!/usr/bin/env python3
"""Living architecture maps: the functional map, the technical map, the ADR history.

The three maps are published twice from ONE set of data:

* on the public site, in the six languages of the site (``/maps/*``, rendered by
  the React components of ``apps/web/src/components/maps``);
* as three self-contained French HTML documents in ``docs/maps/`` — offline
  presentation material, GENERATED by this module from the same data.

The data lives in ``apps/web/src/data/maps/`` because the web container sees
nothing else of the repository:

* ``functional.json``, ``technical.json``, ``history.json`` — the STRUCTURE,
  language-neutral (ids, icons, tones, dependencies, domains, paths, dates);
* ``text/<map>.<lang>.json`` — the WORDS, one file per map and language. French
  is the source; every other language carries, on each unit, the fingerprint
  of the French it translates (``src``);
* ``facts.json`` — GENERATED here: the counts and dates the pages show,
  computed from the tree (a document never restates a value the code owns).

Why a generator and a gate, not hand-written pages
--------------------------------------------------
A schema drawn by hand is true on the day it is drawn. This repository measured
what happens next more than once: six documents quoting six coverage floors, a
capability map describing the product of six months earlier (ADR-229), an
``AGENTS.md`` silently become a strict subset of ``CLAUDE.md``. So the facts the
maps cannot be allowed to miss are CHECKED against the tree, by the same
``task lint:docs`` that gates the rest of the documentation:

* every ADR file has exactly one history entry, and every entry either names a
  file or declares, with a reason, why it has none (ADR-008);
* every backend domain and every infrastructure module is claimed by a brick —
  a new one fails the build until somebody says where it belongs;
* every path a brick points at exists, every screen a brick names is a route;
* every reference between bricks, families, layers, themes and flows resolves,
  and every icon the documents draw is vendored;
* every unit of text exists in every language of the site, and no translation
  is STALE: when the French changes, the fingerprint no longer matches and the
  unit is named until it is translated again (then ``--restamp`` it);
* ``facts.json`` and the three documents are exactly what the data renders —
  edit the JSON, run ``task docs:maps``, commit everything.

``--write`` also stamps the fingerprint of a unit translated for the first time
(it had none). A stale fingerprint is never refreshed implicitly: re-translate,
then ``--restamp map/section/id``.

Existence is decided from the git INDEX, like ``doc_audit.py``: a fresh clone
must reach the same verdict. ``--include-unstaged`` judges tracked files plus
what ``git add -A`` would stage, for the case where the finding is a file you
just created.

Usage (from the repo root):
    python scripts/audit/doc_maps.py                   # check, exit 1 on any finding
    python scripts/audit/doc_maps.py --write           # regenerate facts + documents
    python scripts/audit/doc_maps.py --write --refresh-icons
                                                       # also re-vendor the Lucide subset
    python scripts/audit/doc_maps.py --restamp functional/bricks/f.chat
                                                       # accept re-translated units
    python scripts/audit/doc_maps.py --include-unstaged

Standard library only — no dependencies.
"""

